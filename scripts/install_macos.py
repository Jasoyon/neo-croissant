#!/usr/bin/env python3
"""Install or restore an app bundle with a ZIP backup; never touches chess data."""
import argparse, datetime, hashlib, os, plistlib, re, shutil, subprocess, tempfile, zipfile
from pathlib import Path

def valid(app):
    p = app / 'Contents/Info.plist'
    if not p.is_file() or plistlib.loads(p.read_bytes()).get('CFBundleIdentifier') != 'org.encroissant.app':
        raise ValueError('Not an En Croissant app bundle: ' + str(app))
    subprocess.run(['codesign','--verify','--deep','--strict',str(app)], check=True)

def install(source, destination, backups):
    valid(source)
    if destination.exists(): valid(destination)
    # Do not quit the user's active game or force-kill a process.
    running = subprocess.run(['pgrep','-f',re.escape(str(destination / 'Contents/MacOS/en-croissant'))],capture_output=True)
    if running.returncode == 0:
        raise RuntimeError('Quit En Croissant before installation. No files were replaced.')
    destination.parent.mkdir(parents=True, exist_ok=True)
    backups.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.neo-croissant-', dir=destination.parent) as temp:
        staged = Path(temp) / 'En Croissant.app'
        subprocess.run(['ditto',str(source),str(staged)],check=True)
        valid(staged)
        backup = None
        if destination.exists():
            stamp = datetime.datetime.now().strftime('%Y%m%d-%H%M%S-%f')
            backup = backups / (stamp + '.zip')
            subprocess.run(['ditto','-c','-k','--sequesterRsrc','--keepParent',str(destination),str(backup)],check=True)
            with zipfile.ZipFile(backup) as z:
                if z.testzip(): raise RuntimeError('Backup failed integrity check')
        old = Path(temp) / 'previous.app'
        if destination.exists(): destination.rename(old)
        try:
            staged.rename(destination)
            valid(destination)
        except Exception:
            if destination.exists(): destination.rename(Path(temp) / 'failed.app')
            if old.exists(): old.rename(destination)
            raise
    print('Installed:', destination)
    if backup: print('Restore archive:', backup)

def main():
    p = argparse.ArgumentParser(description=__doc__)
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument('--app', type=Path)
    g.add_argument('--restore', type=Path, help='ZIP generated by this installer')
    p.add_argument('--destination',type=Path,default=Path('/Applications/En Croissant.app'))
    p.add_argument('--backups',type=Path,default=Path.home() / 'Library/Application Support/NeoCroissant/Backups')
    a = p.parse_args()
    if a.restore:
        with zipfile.ZipFile(a.restore) as z:
            for name in z.namelist():
                if name.startswith('/') or '..' in Path(name).parts: p.error('Unsafe archive path')
        with tempfile.TemporaryDirectory() as temp:
            subprocess.run(['ditto','-x','-k',str(a.restore),temp],check=True)
            candidates=list(Path(temp).glob('*.app'))
            if len(candidates)!=1: p.error('Archive must contain one application')
            install(candidates[0],a.destination,a.backups)
    else: install(a.app.resolve(),a.destination,a.backups)

if __name__ == '__main__': main()
